import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { is, SQL } from 'drizzle-orm';
import {
  getTableConfig,
  isPgEnum,
  PgTable,
  type PgColumn,
  type PgEnum,
} from 'drizzle-orm/pg-core';
import { logger } from '../config/logger.js';
import * as schema from '../db/schema/index.js';

/**
 * CLI: regenerate docs/database-schema.md from the Drizzle schema objects.
 *   npm run docs:schema
 *
 * No database connection — the TypeScript schema is the source of truth, so
 * run this after every migration and commit the result with it. Table purposes
 * are hand-written in docs/technical-reference.md §3; this file stays
 * mechanical (columns, keys, indexes, checks, enums).
 */

const OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../docs/database-schema.md',
);

const SCHEMA_NOTES: Record<string, string> = {
  public: 'Sign-in identities and refresh tokens',
  org: 'People, departments, seats, salary, leaves, attendance, payroll, performance, exits, probation, PIP',
  access: 'Owner, modules, batches, grants, requests, audit log',
  ops: 'Assets, custody, requests, gate passes, stock, reminder dedupe',
  ta: 'Hiring: quarterly plans, requisitions, interview rounds, approvals',
};

const sqlText = (value: unknown): string => {
  if (is(value, SQL)) {
    return value.queryChunks
      .map((c) =>
        typeof c === 'object' && c !== null && 'value' in c
          ? ([] as string[]).concat((c as { value: string | string[] }).value).join('')
          : '…',
      )
      .join('');
  }
  if (value instanceof Date) return value.toISOString();
  if (typeof value === 'object') return JSON.stringify(value);
  return String(value);
};

const defaultOf = (col: PgColumn): string => {
  if (col.defaultFn) return '_(set by the app)_';
  if (!col.hasDefault || col.default === undefined) return '';
  return `\`${sqlText(col.default).replaceAll('|', '\\|')}\``;
};

const cell = (s: string) => s.replaceAll('|', '\\|');

const tables = (Object.values(schema) as unknown[])
  .filter((v): v is PgTable => is(v, PgTable))
  .map((t) => ({ table: t, config: getTableConfig(t) }))
  .sort(
    (a, b) =>
      (a.config.schema ?? 'public').localeCompare(b.config.schema ?? 'public') ||
      a.config.name.localeCompare(b.config.name),
  );

const enums = (Object.values(schema) as unknown[])
  .filter((v): v is PgEnum<[string, ...string[]]> => isPgEnum(v))
  .map((e) => ({ name: e.enumName, values: e.enumValues as readonly string[] }))
  .sort((a, b) => a.name.localeCompare(b.name));

const qualified = (t: PgTable) => {
  const c = getTableConfig(t);
  return `${c.schema ?? 'public'}.${c.name}`;
};

const lines: string[] = [
  '# Database schema',
  '',
  '<!-- Generated by `npm run docs:schema` (src/scripts/gen-schema-doc.ts). Do not edit by hand. -->',
  '',
  'PostgreSQL (AWS RDS testing instance). Generated from `src/db/schema/` — the',
  'TypeScript schema and `migrations/` are the source of truth; table purposes and',
  'how they connect are in [`technical-reference.md`](./technical-reference.md) §3.',
  '',
  `**${tables.length} tables · ${enums.length} enums.**`,
  '',
  '| Schema | Tables | Holds |',
  '|---|---|---|',
];
const bySchema = new Map<string, typeof tables>();
for (const t of tables) {
  const s = t.config.schema ?? 'public';
  bySchema.set(s, [...(bySchema.get(s) ?? []), t]);
}
for (const [s, list] of bySchema) {
  lines.push(`| \`${s}\` | ${list.length} | ${SCHEMA_NOTES[s] ?? ''} |`);
}

lines.push('', '## Enums', '', '| Enum | Values |', '|---|---|');
for (const e of enums)
  lines.push(`| \`${e.name}\` | ${e.values.map((v) => `\`${v}\``).join(', ')} |`);

for (const [s, list] of bySchema) {
  lines.push('', `## \`${s}\``);
  for (const { config } of list) {
    lines.push(
      '',
      `### ${config.name}`,
      '',
      '| Column | Type | Null | Default | Notes |',
      '|---|---|---|---|---|',
    );
    const fkByColumn = new Map<string, string>();
    for (const fk of config.foreignKeys) {
      const ref = fk.reference();
      ref.columns.forEach((c, i) => {
        fkByColumn.set(
          c.name,
          `→ \`${qualified(ref.foreignTable)}.${ref.foreignColumns[i]?.name ?? '?'}\`${
            fk.onDelete && fk.onDelete !== 'no action'
              ? ` (on delete ${fk.onDelete})`
              : ''
          }`,
        );
      });
    }
    for (const col of config.columns) {
      const notes = [
        col.primary ? 'PK' : '',
        col.isUnique ? 'unique' : '',
        fkByColumn.get(col.name) ?? '',
      ]
        .filter(Boolean)
        .join(' · ');
      lines.push(
        `| \`${col.name}\` | ${cell(col.getSQLType())} | ${col.notNull ? '' : 'yes'} | ${defaultOf(col)} | ${notes} |`,
      );
    }
    const extra: string[] = [];
    for (const pk of config.primaryKeys) {
      extra.push(`- Primary key (${pk.columns.map((c) => `\`${c.name}\``).join(', ')})`);
    }
    for (const u of config.uniqueConstraints) {
      extra.push(`- Unique (${u.columns.map((c) => `\`${c.name}\``).join(', ')})`);
    }
    for (const idx of config.indexes) {
      const cols = idx.config.columns
        .map((c) =>
          'name' in c && typeof c.name === 'string' ? `\`${c.name}\`` : 'expr',
        )
        .join(', ');
      extra.push(
        `- ${idx.config.unique ? 'Unique index' : 'Index'} \`${idx.config.name ?? ''}\` (${cols})${
          idx.config.where ? ` where \`${cell(sqlText(idx.config.where))}\`` : ''
        }`,
      );
    }
    for (const ch of config.checks) {
      extra.push(`- Check \`${ch.name}\`: \`${cell(sqlText(ch.value))}\``);
    }
    if (extra.length) lines.push('', ...extra);
  }
}

writeFileSync(OUT, `${lines.join('\n')}\n`);
logger.info(
  { out: OUT, tables: tables.length, enums: enums.length },
  'database-schema.md written',
);
